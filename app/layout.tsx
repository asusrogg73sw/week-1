import type { Metadata } from "next";
import { Geist, Geist_Mono, Raleway, Noto_Serif, Public_Sans } from "next/font/google";
import "./globals.css";
import Navbar from "@/components/Navbar";
import { cn } from "@/lib/utils";

const publicSansHeading = Public_Sans({subsets:['latin'],variable:'--font-heading'});

const notoSerif = Noto_Serif({subsets:['latin'],variable:'--font-serif'});

const raleway = Raleway({subsets:['latin'],variable:'--font-sans'});

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={cn("h-full", "antialiased", geistSans.variable, geistMono.variable, raleway.variable, "font-serif", notoSerif.variable, publicSansHeading.variable)}
    >
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
        try {
          const savedTheme = localStorage.getItem('theme');

          const shouldBeDark =
            savedTheme === 'dark' ||
            (savedTheme === null &&
              window.matchMedia('(prefers-color-scheme: dark)').matches);

          document.documentElement.classList.toggle(
            'dark',
            shouldBeDark
          );
        } catch (_) {}
      `,
          }}
        />
      </head>

      {/* 
        Changes made:
        1. Added `bg-background text-foreground` so theme colors apply globally.
        2. Added `font-sans` to ensure Geist font is the default typography.
      */}
      <body className="min-h-full flex flex-col bg-background text-foreground font-sans">
        <Navbar />

        {/* Main wrapper to push footer down if added later */}
        <main className="flex-1">{children}</main>
      </body>
    </html>
  );
}
